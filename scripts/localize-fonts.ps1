# Downloads Space Grotesk + IBM Plex Mono (latin + cyrillic subsets) from Google Fonts,
# writes fonts.css and switches every *.html from Google Fonts to the local copy
# (also removes fonts.googleapis.com / fonts.gstatic.com from the CSP).
# Run from anywhere:  powershell -ExecutionPolicy Bypass -File scripts\localize-fonts.ps1
$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)
$ua   = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'
$cssUrl = 'https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=Space+Grotesk:wght@400;500;700&display=swap'

$css = (Invoke-WebRequest -Uri $cssUrl -UserAgent $ua -UseBasicParsing).Content
$fontsDir = Join-Path $root 'fonts'
New-Item -ItemType Directory -Force -Path $fontsDir | Out-Null

$keep = @('latin', 'cyrillic')
$out  = New-Object System.Text.StringBuilder
[void]$out.AppendLine('/* Generated by scripts/localize-fonts.ps1 */')
$count = 0

$rx = [regex]'/\*\s*([a-z\-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})'
foreach ($m in $rx.Matches($css)) {
    if ($keep -notcontains $m.Groups[1].Value) { continue }
    $block = $m.Groups[2].Value
    $u = [regex]::Match($block, 'url\((https://[^)]+\.woff2)\)')
    if (-not $u.Success) { continue }
    $remote = $u.Groups[1].Value
    $name = [IO.Path]::GetFileName(([Uri]$remote).AbsolutePath)
    $dest = Join-Path $fontsDir $name
    if (-not (Test-Path $dest)) {
        Invoke-WebRequest -Uri $remote -OutFile $dest -UserAgent $ua -UseBasicParsing
    }
    [void]$out.AppendLine($block.Replace($remote, "fonts/$name"))
    $count++
}
if ($count -eq 0) { throw 'No @font-face blocks found - nothing was changed.' }
[IO.File]::WriteAllText((Join-Path $root 'fonts.css'), $out.ToString(), $utf8)
Write-Host "Saved $count font files + fonts.css"

foreach ($f in Get-ChildItem -Path $root -Filter *.html) {
    $t = [IO.File]::ReadAllText($f.FullName, $utf8)
    $n = [regex]::Replace($t, '[ \t]*<link rel="preconnect" href="https://fonts\.(googleapis|gstatic)\.com"[^>]*>\r?\n', '')
    $n = [regex]::Replace($n, '<link href="https://fonts\.googleapis\.com/css2[^"]*" rel="stylesheet"[^>]*>', '<link rel="stylesheet" href="fonts.css">')
    $n = $n.Replace(' https://fonts.googleapis.com', '').Replace(' https://fonts.gstatic.com', '')
    if ($n -ne $t) {
        [IO.File]::WriteAllText($f.FullName, $n, $utf8)
        Write-Host "patched $($f.Name)"
    }
}
Write-Host 'Done. Check the site locally, then commit fonts/, fonts.css and the *.html changes.'
